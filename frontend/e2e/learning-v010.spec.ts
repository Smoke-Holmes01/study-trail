import { expect, test } from '@playwright/test';

test('v010 template publication, independent adoption, editable learning content and optional resource import', async ({ browser, page }, info) => {
  test.setTimeout(180000);
  const baseURL = info.project.use.baseURL!;
  const origin = new URL(baseURL).origin;
  const adminContext = await browser.newContext({ baseURL });
  const adminPage = await adminContext.newPage();
  const errors: string[] = [];
  for (const surface of [page, adminPage]) surface.on('pageerror', e => errors.push(e.message));
  const unique = Date.now().toString(36);
  const templateName = '矩阵模板-' + unique;
  const filename = '矩阵资料-' + unique + '.txt';
  try {
    await adminPage.goto('/admin/login');
    await adminPage.getByLabel('管理员账号').fill('e2e_admin');
    await adminPage.getByLabel('密码', { exact: true }).fill('e2e-admin-password');
    await adminPage.getByRole('button', { name: '登录管理端' }).click();
    await adminPage.getByRole('link', { name: '子智能体配置', exact: true }).click();
    await expect(adminPage.getByRole('button', { name: '编辑角色职责与能力' })).toHaveCount(5);
    await adminPage.getByRole('button', { name: '编辑角色职责与能力' }).first().click();
    await expect(adminPage.getByLabel('职责提示词')).toBeVisible();
    await adminPage.getByRole('button', { name: '取消', exact: true }).click();
    await adminPage.getByRole('link', { name: '智能体模板', exact: true }).click();
    await adminPage.getByRole('button', { name: '新建模板', exact: true }).click();
    await adminPage.getByLabel('模板名称').fill(templateName);
    await adminPage.getByLabel('模板描述').fill('隔离浏览器回归模板，仅用于测试。');
    const createdResponse = adminPage.waitForResponse(r => r.url().endsWith('/api/admin/agent-templates') && r.request().method() === 'POST');
    await adminPage.getByRole('button', { name: '创建草稿', exact: true }).click();
    const template = (await (await createdResponse).json()).data;
    const editor = adminPage.getByRole('dialog', { name: templateName });
    await expect(editor.getByLabel('系统提示词')).toBeVisible();
    await editor.getByLabel('系统提示词').fill('根据用户目标解释矩阵，严格遵守引用权限。');
    const models = (await (await adminPage.request.get('/api/admin/configs/model?limit=100')).json()).data.items;
    const model = models.find((m: any) => m.enabled && m.payload.model_kind === 'generative');
    expect(model).toBeTruthy();
    await editor.getByLabel('生成模型', { exact: true }).selectOption(model.stable_id);
    await editor.getByLabel('计划名称').fill('矩阵入门计划');
    await editor.getByLabel('学习目标', { exact: true }).fill('理解矩阵乘法');
    await editor.getByLabel('阶段名称').fill('矩阵基础');
    await editor.getByLabel('阶段目标').fill('掌握维度与乘法');
    await editor.getByLabel('知识点（每行一项）').fill('维度\n矩阵乘法');
    await editor.getByLabel('任务 1', { exact: true }).fill('完成矩阵乘积例题');
    await editor.getByRole('button', { name: '添加练习', exact: true }).click();
    await editor.getByLabel('题目 1', { exact: true }).fill('单位矩阵乘以矩阵A等于什么？');
    await editor.getByLabel('模板预置答案（可选）').fill('预置参考答案：等于矩阵A。');
    await editor.getByLabel('解析（可选）', { exact: true }).fill('单位矩阵不改变乘积。');
    await editor.locator('input[type=file]').setInputFiles({ name: filename, mimeType: 'text/plain', buffer: Buffer.from('单位矩阵与任何相容矩阵相乘，结果仍是原矩阵。矩阵乘法要求维度匹配。') });
    await expect.poll(async () => {
      const response = await adminPage.request.get(`/api/admin/agent-templates/${template.id}/assets?limit=100`);
      return (await response.json()).data.items.find((a: any) => a.filename === filename)?.status;
    }, { timeout: 60000 }).toBe('ready');
    await editor.getByRole('button', { name: '刷新处理状态', exact: true }).click();
    const reference = editor.getByRole('group', { name: '参考资料', exact: true }).first();
    await expect(reference.getByRole('checkbox', { name: filename, exact: true })).toBeVisible();
    await reference.getByRole('checkbox', { name: filename, exact: true }).check();
    await editor.getByRole('group', { name: '题目资料来源', exact: true }).getByRole('checkbox', { name: filename, exact: true }).check();
    await editor.getByRole('button', { name: '保存草稿', exact: true }).click();
    await expect(editor.getByRole('button', { name: '发布已保存版本', exact: true })).toBeEnabled();
    await editor.getByRole('button', { name: '发布已保存版本', exact: true }).click();
    await editor.getByRole('button', { name: '确认发布', exact: true }).click();
    await expect(editor.getByText('版本已发布。', { exact: true })).toBeVisible();
    await adminPage.screenshot({ path: info.outputPath('template-published.png') });

    const login = 'v010_' + unique;
    const password = 'v010-browser-test-password';
    expect((await page.request.post('/api/v1/auth/register', { headers: { Origin: origin }, data: { login, password, confirm_password: password } })).status()).toBe(201);
    expect((await page.request.post('/api/v1/auth/login', { headers: { Origin: origin }, data: { login, password } })).status()).toBe(200);
    await page.goto('/agents');
    await page.getByRole('button', { name: '创建智能体', exact: true }).click();
    await page.getByRole('button', { name: templateName, exact: true }).click();
    const preview = page.getByRole('dialog', { name: templateName });
    await expect(preview.getByText('预置参考答案：等于矩阵A。', { exact: true })).toHaveCount(0);
    await preview.getByRole('button', { name: '查看模板已有答案与解析' }).click();
    await expect(preview.getByText('预置参考答案：等于矩阵A。', { exact: true })).toBeVisible();
    await preview.getByLabel('个人智能体名称').fill('我的矩阵副本');
    const adoptedResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/template-adoptions') && r.request().method() === 'POST');
    await preview.getByRole('button', { name: '采用模板并创建个人副本' }).click();
    const adoption = (await (await adoptedResponse).json()).data;
    await expect(page.getByRole('dialog', { name: '模板资料导入' })).toContainText('尚未导入模板资料');
    await page.getByRole('button', { name: '关闭弹窗' }).click();
    await page.getByRole('button', { name: '学习内容', exact: true }).click();
    const learning = page.getByRole('dialog', { name: '学习内容' });
    await expect(learning.getByRole('button', { name: /模板资料未导入/ })).toBeDisabled();
    await learning.getByRole('button', { name: '直接编辑', exact: true }).click();
    await learning.getByLabel('学习目标', { exact: true }).fill('取消后不保存');
    await learning.getByRole('button', { name: '取消编辑', exact: true }).click();
    await expect(learning.getByText('理解矩阵乘法', { exact: true })).toBeVisible();
    await learning.getByRole('button', { name: '直接编辑', exact: true }).click();
    await learning.getByLabel('学习目标', { exact: true }).fill('个人修改后的学习目标');
    await learning.getByRole('button', { name: '保存计划', exact: true }).click();
    await expect(learning.getByText('个人修改后的学习目标', { exact: true })).toBeVisible();
    await learning.getByRole('button', { name: '练习集', exact: true }).click();
    await expect(learning.getByText('预置参考答案：等于矩阵A。', { exact: true })).toHaveCount(0);
    await learning.getByRole('button', { name: '查看答案与解析', exact: true }).click();
    await expect(learning.getByText('预置参考答案：等于矩阵A。', { exact: true })).toBeVisible();
    await expect(learning.locator('.learning-answer').getByRole('button', { name: new RegExp(filename) })).toBeDisabled();
    await learning.getByRole('button', { name: '编辑练习', exact: true }).click();
    await learning.getByLabel('题干', { exact: true }).fill('个人修改：A乘以单位矩阵等于什么？');
    await learning.getByRole('button', { name: '保存练习', exact: true }).click();
    await expect(learning.getByText('个人修改：A乘以单位矩阵等于什么？', { exact: true })).toBeVisible();
    await page.setViewportSize({ width: 440, height: 763 });
    await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; });
    await expect(learning.getByRole('button', { name: '编辑练习', exact: true })).toBeEnabled();
    await expect(learning.getByRole('button', { name: '编辑练习', exact: true })).toHaveCSS('background-color', 'rgb(45, 51, 46)');
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(440);
    await page.screenshot({ path: info.outputPath('learning-mobile-dark.png') });
    await page.getByRole('button', { name: '关闭弹窗' }).click();
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.getByRole('button', { name: '模板资料导入状态', exact: true }).click();
    const importer = page.getByRole('dialog', { name: '模板资料导入' });
    await importer.getByLabel('新知识库名称', { exact: true }).fill('个人模板资料-' + unique);
    await importer.getByRole('button', { name: '开始补导入', exact: true }).click();
    await expect(importer.getByRole('heading', { name: /资料导入 · (成功|完成)/ })).toBeVisible({ timeout: 60000 });
    await page.screenshot({ path: info.outputPath('template-import-completed.png') });
    const copied = (await (await page.request.get(`/api/v1/plans/${adoption.plan_ids[0]}`)).json()).data;
    expect(copied.content.goal).toBe('个人修改后的学习目标');
    expect(copied.sources.every((s: any) => s.status !== 'template_not_imported')).toBe(true);
    const sourceTemplate = (await (await adminPage.request.get(`/api/admin/agent-templates/${template.id}`)).json()).data;
    expect(sourceTemplate.versions.find((v: any) => v.id === sourceTemplate.published_version_id).payload.plan.goal).toBe('理解矩阵乘法');
    expect(errors).toEqual([]);
  } finally { await adminContext.close(); }
});
